# provenance and files

def sha256(p: Path) -> str | None:
    return M.sha256(Path(p)) if Path(p).exists() else None


def git(*args: str, cwd: Path = ROOT) -> str | None:
    try:
        r = subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True, timeout=30)
        return r.stdout.strip() if r.returncode == 0 else None
    except Exception:
        return None


def code_info() -> dict:
    status = git("status", "--porcelain", "--", *CODE_FILES)
    return {"commit": git("rev-parse", "HEAD"), "changed_files": None if status is None else
            [x[3:] for x in status.splitlines() if x.strip()],
            "sha256": {f: sha256(ROOT / f) for f in CODE_FILES}}


def read(p: Path):
    try:
        return json.loads(Path(p).read_text())
    except (OSError, ValueError):
        return None


def write(p: Path, obj) -> None:
    p = Path(p)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, indent=1, default=str, ensure_ascii=False) + "\n")
    os.replace(tmp, p)


def read_jsonl(p: Path) -> list[dict]:
    rows = []
    if Path(p).exists():
        for line in Path(p).read_text().splitlines():
            try:
                rows.append(json.loads(line))
            except ValueError:
                pass
    return rows


def append_jsonl(p: Path, row: dict) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "a") as f:
        f.write(json.dumps(row, default=str, ensure_ascii=False) + "\n")


def last_rows(p: Path) -> dict[str, dict]:
    return {r["run_id"]: r for r in read_jsonl(p) if "run_id" in r}


def utc() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def settings_of(a, events, words, key_used: str, midi: dict | None) -> dict:
    return {"melody": melody_text(events), "melody_input": None if midi else a.melody, "midi": midi,
            "lyric": " ".join(words), "bpm": int(a.bpm), "voice": a.voice, "draws": int(a.draws), "seed": int(a.seed),
            "key": a.key, "key_used": key_used, "compare_no_clock": bool(a.compare), "device": a.device}


def folder_name(settings: dict, words: list[str]) -> str:
    slug = "-".join(re.sub(r"[^a-z]", "", w.lower()) for w in words[:4]).strip("-") or "melody"
    h = hashlib.sha256(json.dumps({k: v for k, v in settings.items() if k != "melody_input"}, sort_keys=True).encode())
    return f"{slug[:40]}-{h.hexdigest()[:8]}"


# planning (main environment)

def load_inputs(a) -> tuple[list, list[str], dict | None, list[str]]:
    """(events, words, MIDI info, notes) from the command line; raises InputError. Puts the key's case right."""
    notes = []
    a.key = "auto" if (a.key or "").strip().lower() == "auto" else (norm_key(a.key) or a.key)
    if a.midi:
        if a.melody:
            raise InputError("give the melody as text or as a MIDI file, not both")
        events, midi = parse_midi(a.midi)
        if midi["tempo_bpm"] and abs(midi["tempo_bpm"] - int(a.bpm)) > 0.5:
            notes.append(f"the MIDI file's tempo is {midi['tempo_bpm']:g} BPM; the tool sings at {int(a.bpm)} BPM "
                         f"(set the tempo to {round(midi['tempo_bpm'])} to keep the file's)")
    else:
        events, midi = parse_melody(a.melody), None
    return events, split_lyric(a.lyric), midi, notes


def guide_seconds(item: dict) -> float:
    """About how long the guide, and so every take, lasts: the last note's end plus FluidSynth's tail."""
    last = item["melody"]["notes"][-1]
    return (last["start"] + last["dur"]) * 60.0 / float(item["melody"]["bpm"]) + GUIDE_TAIL_S


def describe(item: dict, events, words: list[str], warnings: list[str], seconds: float | None = None) -> str:
    spb = 60.0 / item["melody"]["bpm"]
    took = f"{seconds:.1f} s, the guide's length" if seconds else f"about {guide_seconds(item):.0f} s, as long as the guide"
    lines = [f"{len(words)} words on {len(item['melody']['notes'])} notes, {int(item['melody']['bpm'])} BPM, key "
             f"{item['key']}; the takes last {took}",
             "  word            note   beats  onset s"]
    for w, n, (_, d) in zip(words, item["melody"]["notes"], pitched(events)):
        lines.append(f"  {w[:14]:14s}  {note_name(n['pitch']):5s} {d:6.3g}  {n['start'] * spb:7.2f}")
    lines += [f"warning: {w}" for w in warnings]
    return "\n".join(lines)


def resolve_key(key: str, events) -> str:
    """The key ACE-Step is told: estimate_key for auto, else the given key with its case put right."""
    return estimate_key(events) if key == "auto" else norm_key(key)


def make_plan(a, out_root: Path) -> tuple[Path, dict, list]:
    """Check the input, build the item, render the guide and write plan.json in the run's folder. The same
    settings give the same folder; a folder holding other settings is refused."""
    events, words, midi, notes = load_inputs(a)
    warnings = notes + check_inputs(events, words, a.bpm, a.voice, a.draws, a.key)
    key = resolve_key(a.key, events)
    warnings += key_warning(events, key)
    item = build_item(events, words, int(a.bpm), key)
    settings = settings_of(a, events, words, key, midi)
    rundir = Path(out_root) / (a.name or folder_name(settings, words))
    old = read(rundir / "plan.json")
    if old is not None:
        if {k: v for k, v in old["settings"].items() if k != "melody_input"} != \
                {k: v for k, v in settings.items() if k != "melody_input"}:
            raise InputError(f"{rundir} holds a run with other settings; choose another --name")
        print(f"resuming {rundir}", flush=True)
    rundir.mkdir(parents=True, exist_ok=True)
    _, _, guide_sha = M.render_one(item, "oohs", rundir)
    if old is not None and old["guide"]["sha256"] != guide_sha:
        raise SetupError(f"the guide rendered now differs from the one in {rundir}/plan.json (another soundfont?)")
    sf2, b2 = M.soundfont(), P.read_json(P.GUIDES_JSON)
    sf2_is_b2s = sf2["soundfont_sha256"] == b2["soundfont_sha256"]
    if not sf2_is_b2s:
        warnings.append(f"the guide is rendered with {sf2['soundfont']} (sha256 {str(sf2['soundfont_sha256'])[:8]}), "
                        f"not B2's {b2['soundfont']} ({b2['soundfont_sha256'][:8]}), so it sounds different from B2's "
                        "guides; set DACAPO_SF2 to FluidR3_GM.sf2 (apt package fluid-soundfont-gm)")
    runs = make_runs(item, a.draws, a.seed, a.voice, a.compare)
    plan = {"tool": "sing my melody (experiments/sing/sing.py)", "utc": old["utc"] if old else utc(),
            "settings": settings, "warnings": warnings, "item": item,
            "guide": {"file": P.guide_path(rundir, ITEM_ID, "oohs").name, "sha256": guide_sha, "program": P.GUIDES["oohs"],
                      "seconds": wav_seconds(P.guide_path(rundir, ITEM_ID, "oohs")), **sf2,
                      "soundfont_is_b2s": sf2_is_b2s, "b2_soundfont_sha256": b2["soundfont_sha256"]},
            "recipe": {"config": S_STAR, **P.parse(S_STAR), "heads": {str(k): v for k, v in R.ALIGN.items()},
                       "steps": P.STEPS, "shift": P.SHIFT, "task": "cover-nofsq", "cover_strength": 3 / P.STEPS,
                       "caption": caption(a.voice), "comparison": S_B0 if a.compare else None},
            "seeds": {"tag": TAG, "derivation": DERIVATION, "item_id": str(int(a.seed)),
                      "draws": [{"draw": r, "take": r + 1, **dict(zip(("dit_seed", "rng_seed"), seeds(a.seed, r)))}
                                for r in range(int(a.draws))]},
            "runs": runs, "code": code_info()}
    if old is None:
        write(rundir / "plan.json", plan)
    return rundir, plan, events


def key_warning(events, key: str) -> list[str]:
    out = outside_key(events, key)
    return [f"notes outside the scale of {key}, the key ACE-Step is told: {', '.join(out)} (B2's melodies kept to "
            "their key's scale)"] if out else []


def wav_seconds(p: Path) -> float:
    import soundfile as sf
    return round(float(sf.info(str(p)).duration), 3)


# generation (ACE-Step environment)

def gen(rundir: Path, device: str) -> int:
    """Every planned run not generated yet, with run_b2.generate_run; one ledger row per attempt."""
    import torch

    plan = read(rundir / "plan.json")
    if plan is None:
        raise SetupError(f"no plan.json in {rundir}")
    if device == "cuda" and not torch.cuda.is_available():
        raise SetupError("no CUDA GPU: the tool needs a GPU runtime (Runtime > Change runtime type > GPU in Colab)")
    if device == "cuda" and torch.cuda.get_device_capability(0)[0] < 8:
        raise SetupError(OLD_GPU.format(gpu=torch.cuda.get_device_name(0)))

    from dacapo import ace  # puts $ACESTEP_REPO on the path
    import run_b2 as RB
    from acestep.core.scoring.dit_alignment import MusicStampsAligner
    from dacapo.attn_bias import lyric_keys
    ledger = rundir / "ledger.jsonl"
    done = {rid for rid, row in last_rows(ledger).items() if row.get("status") == "ok" and
            sha256(rundir / f"{rid}.wav") == row.get("wav_sha256")}
    todo = [r for r in plan["runs"] if r["run_id"] not in done]
    if not todo:
        print("every planned take is generated", flush=True)
        return 0
    item = plan["item"]
    guide = P.guide_path(rundir, ITEM_ID, "oohs")
    if sha256(guide) != plan["guide"]["sha256"]:
        raise SetupError("the guide differs from plan.json")
    det = ace.setup_determinism()
    try:
        h = ace.load(device)
    except Exception as exc:
        raise SetupError(f"ACE-Step did not load: {exc!r}") from exc
    if {int(k): list(v) for k, v in h.custom_layers_config.items()} != R.ALIGN:
        raise SetupError(f"unexpected alignment heads {h.custom_layers_config}")
    if getattr(h.model.config, "_attn_implementation", None) != "sdpa":
        raise SetupError(f"ACE-Step chose {h.model.config._attn_implementation} attention, not sdpa as in Run B. "
                         + OLD_GPU.format(gpu=torch.cuda.get_device_name(0) if device == "cuda" else device))
    try:
        lay = lyric_keys(h, MusicStampsAligner(h.text_tokenizer), item["lyrics"])
    except ValueError as exc:
        raise InputError(f"ACE-Step's tokenizer splits the lyric into other words: {exc}") from None
    if len(lay["keys"]) != len(item["melody"]["notes"]):
        raise SetupError(f"ACE-Step reads {len(lay['keys'])} words for {len(item['melody']['notes'])} notes")
    long_words = [w for w, k in zip(lay["words"], lay["keys"]) if len(k) > 2]
    if long_words:
        print(f"warning: words of 3 or more tokens (B2 used 1-2): {', '.join(long_words)}", flush=True)
    write(rundir / "gen_setup.json", {"utc": utc(), "device": device, "determinism": det, "lyric_layout": lay,
                                      "spans": spans(item, lay["keys"]), "words_of_3_or_more_tokens": long_words,
                                      "ace_commit": git("rev-parse", "HEAD", cwd=Path(os.environ.get("ACESTEP_REPO", "."))),
                                      "dtype": str(h.dtype)})
    ok = 0
    for run in todo:
        try:
            row, _ = RB.generate_run(h, run, lay, item, rundir, rundir)
            want = P.HOOK_CALLS if run["hooked"] else 0
            if row["hook_calls"] != want or (run["hooked"] and not row["max_key"] < row["n_lyr"]):
                raise RuntimeError(f"{row['hook_calls']} clock calls (expected {want}), max key {row['max_key']}")
            for x in ("pred", "target"):
                (rundir / f"{run['run_id']}.{x}.npy").unlink(missing_ok=True)
            append_jsonl(ledger, {**row, "take": run["take"], "recipe": run["recipe"], "caption": run["caption"],
                                  "device": device, "utc": utc()})
            ok += 1
            print(f"{run['run_id']:>15s} generated in {row['gen_seconds']:.1f} s (clock calls {row['hook_calls']})",
                  flush=True)
        except Exception as exc:  # one failed take must not stop the others
            append_jsonl(ledger, {"run_id": run["run_id"], "status": "failed", "error": repr(exc),
                                  "traceback": traceback.format_exc(), "utc": utc()})
            print(f"{run['run_id']:>15s} FAILED: {exc!r}", flush=True)
        finally:
            if device == "cuda":
                torch.cuda.empty_cache()
    return 0 if ok or done else 3


