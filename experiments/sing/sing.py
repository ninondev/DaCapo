# melody

def note_name(p: int) -> str:
    return f"{SHARP_NAMES[p % 12]}{p // 12 - 1}"


def parse_length(s: str, token: str) -> float:
    try:
        v = Fraction(s.strip())
    except (ValueError, ZeroDivisionError):
        raise InputError(f"{token!r}: the length {s!r} is not a number of beats (write 1, 0.5 or 3/2)") from None
    if not 0 < v <= 16:
        raise InputError(f"{token!r}: a length must be more than 0 and at most 16 beats")
    if v < Fraction(1, GRID):
        raise InputError(f"{token!r}: a length must be at least 1/{GRID} beat (the grid MIDI files are read on)")
    return float(v)


def parse_melody(text: str) -> list[tuple[int | None, float]]:
    """Notes as text -> [(MIDI pitch or None for a rest, length in beats)]. A note is a name with octave (C4 is
    MIDI 60; sharps #, flats b) or a MIDI number, then a colon and its length in beats (1, 0.5, 3/2); without
    a length it lasts one beat. R (or rest, or -) is a rest. Commas and bar lines | are ignored."""
    tokens = [t for t in re.split(r"[\s,|]+", text or "") if t]
    if not tokens:
        raise InputError("the melody is empty: write notes like C4:1 D4:1 E4:2")
    out = []
    for t in tokens:
        m = _TOKEN.match(t)
        if not m:
            raise InputError(f"{t!r} is not a note: write a name with octave and a length, like C4:1, F#4:0.5 or "
                             "Bb3:2, or R:1 for a rest")
        length = parse_length(m.group("len"), t) if m.group("len") is not None else 1.0
        if m.group("rest"):
            out.append((None, length))
            continue
        if m.group("num"):
            p = int(m.group("num"))
        else:
            p = 12 * (int(m.group("oct")) + 1) + STEP_NAMES[m.group("name").upper()] + ACCIDENTALS[m.group("acc") or ""]
        if not 0 <= p <= 127:
            raise InputError(f"{t!r} is outside MIDI 0-127")
        out.append((p, length))
    return out


def melody_text(events: list[tuple[int | None, float]]) -> str:
    """The inverse of parse_melody (lengths as fractions where they are not whole)."""
    def ln(x: float) -> str:
        f = Fraction(x).limit_denominator(GRID * 4)
        return str(f.numerator) if f.denominator == 1 else f"{f.numerator}/{f.denominator}"
    return " ".join(f"{'R' if p is None else note_name(p)}:{ln(d)}" for p, d in events)


def parse_midi(path: str | Path) -> tuple[list[tuple[int | None, float]], dict]:
    """A MIDI file with one monophonic track -> events as parse_melody gives them, read in beats (ticks over the
    file's resolution), so the file's tempo does not change them. Positions are rounded to 1/24 beat. A note
    lasts until the next onset unless a gap of half a beat or more follows it, which becomes a rest; the last
    note keeps its own length. Whole silent bars (4 beats) before the first note are dropped."""
    import pretty_midi

    try:
        pm = pretty_midi.PrettyMIDI(str(path))
    except Exception as exc:
        raise InputError(f"cannot read the MIDI file {Path(path).name}: {exc}") from None
    tracks = [i for i in pm.instruments if i.notes and not i.is_drum]
    if len(tracks) != 1:
        raise InputError(f"the MIDI file has {len(tracks)} tracks with notes; the tool needs exactly one monophonic track")
    notes = sorted(tracks[0].notes, key=lambda n: (n.start, n.pitch))

    def ticks(t: float) -> int:  # position in 1/GRID beats
        return int(round(pm.time_to_tick(t) / pm.resolution * GRID))
    on, off = [ticks(n.start) for n in notes], [ticks(n.end) for n in notes]
    for j in range(len(notes) - 1):
        if on[j + 1] <= on[j]:
            raise InputError(f"two notes start together at beat {on[j] / GRID:g}: the track is not monophonic")
        if off[j] - on[j + 1] > MIDI_OVERLAP_MAX * GRID:
            raise InputError(f"the notes at beats {on[j] / GRID:g} and {on[j + 1] / GRID:g} overlap: the track is not "
                             "monophonic")
    events: list[tuple[int | None, float]] = []
    lead = (on[0] // (4 * GRID)) * 4 * GRID
    if on[0] > lead:
        events.append((None, (on[0] - lead) / GRID))
    for j, n in enumerate(notes):
        dur = max(off[j] - on[j], 1)
        if j + 1 == len(notes):
            events.append((int(n.pitch), dur / GRID))
            continue
        ioi = on[j + 1] - on[j]
        if ioi - dur >= MIDI_REST_MIN * GRID:
            events += [(int(n.pitch), dur / GRID), (None, (ioi - dur) / GRID)]
        else:
            events.append((int(n.pitch), ioi / GRID))
    _, tempi = pm.get_tempo_changes()
    info = {"file": Path(path).name, "sha256": M.sha256(Path(path)), "resolution": pm.resolution,
            "tempo_bpm": round(float(tempi[0]), 3) if len(tempi) else None, "notes": len(notes),
            "dropped_leading_beats": lead / GRID}
    return events, info


def pitched(events) -> list[tuple[int, float]]:
    return [(p, d) for p, d in events if p is not None]


def estimate_key(events) -> str:
    """The key to tell ACE-Step when the user gives none. B2 always gave the major key its melody was written
    in, and every note lay in that key's scale, so keys are ranked by (1) the fewest beats of notes outside
    the key's scale (major; minor is natural minor plus its raised 7th), (2) major before minor, (3) the
    Krumhansl-Kessler correlation with the melody's pitch classes weighted by written length, (4) the lower
    tonic. On B2's 24 test and E4's 12 dev melodies it gives a key whose scale holds every note."""
    hist = np.zeros(12)
    for p, d in pitched(events):
        hist[p % 12] += d
    if not hist.any():
        return "C major"
    flat = np.allclose(hist, hist[0])
    best = None
    for mi, (mode, scale, prof, names) in enumerate((("major", MAJOR_SCALE, KK_MAJOR, SHARP_NAMES),
                                                     ("minor", MINOR_SCALE, KK_MINOR, MINOR_NAMES))):
        for t in range(12):
            outside = round(float(sum(hist[(t + i) % 12] for i in range(12) if i not in scale)), 9)
            r = 0.0 if flat else round(float(np.corrcoef(hist, np.roll(prof, t))[0, 1]), 12)
            rank = (-outside, -mi, r)
            if best is None or rank > best[0]:
                best = (rank, f"{names[t]} {mode}")
    return best[1]


def outside_key(events, key: str) -> list[str]:
    """Names of the melody's notes whose pitch class is outside the key's scale."""
    m = re.fullmatch(r"([A-G])(#|b)? (major|minor)", key)
    tonic = (STEP_NAMES[m.group(1)] + ACCIDENTALS[m.group(2) or ""]) % 12
    scale = MAJOR_SCALE if m.group(3) == "major" else MINOR_SCALE
    return [note_name(p) for p in sorted({p for p, _ in pitched(events) if (p - tonic) % 12 not in scale})]


def norm_key(key: str) -> str | None:
    """'d major', 'F♯ MINOR' -> 'D major', 'F# minor'; None if it is not a key."""
    m = re.fullmatch(r"\s*([A-Ga-g])\s*(#|b|♯|♭)?\s+(major|minor)\s*", key or "", flags=re.IGNORECASE)
    if not m:
        return None
    acc = {"♯": "#", "♭": "b", "B": "b"}.get(m.group(2) or "", m.group(2) or "")
    return f"{m.group(1).upper()}{acc} {m.group(3).lower()}"


def valid_key(key: str) -> bool:
    return norm_key(key) is not None


