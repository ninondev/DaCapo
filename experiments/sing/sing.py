def counts(share: float, n: int) -> str:
    return f"{int(round(float(share) * n))}/{n}"


def result_doc(plan: dict, gens: dict[str, dict], scores: dict[str, dict], scorer: dict, files: dict[str, dict]) -> dict:
    """The output JSON: settings, seeds, code, every take with B2's per-clip values, and the take B2's selector
    keeps for each recipe. gens and scores: run_id -> last ledger row and score row; files: run_id -> paths."""
    import score_b2 as S

    item = plan["item"]
    n_notes, n_words = len(item["melody"]["notes"]), len(item["words"])
    takes = []
    for run in plan["runs"]:
        g, s = gens.get(run["run_id"]), scores.get(run["run_id"])
        ok = bool(g and g.get("status") == "ok")
        if s is not None and (not ok or s.get("wav_sha256") != g.get("wav_sha256")):
            s = None
        v = S.clip(s, g.get("peak_before_norm"), item) if ok else dict(S.MISSING)
        takes.append({"run_id": run["run_id"], "take": run["take"], "draw": run["draw"], "recipe": run["recipe"],
                      "config": run["config"], "dit_seed": run["dit_seed"], "rng_seed": run["rng_seed"],
                      "status": "scored" if v["scored"] else ("generated, not scored" if ok else "not generated"),
                      "error": (s or {}).get("error") or (None if ok else (g or {}).get("error")),
                      "q": v["q"], "npa_v": v["npa_v"], "wr": v["wr"], "gate": v["gate"], "joint": v["joint"],
                      "strict": v["strict"], "notes_right": counts(v["npa_v"], n_notes),
                      "words_recognised": counts(v["wr"], n_words), "whisper_text": (s or {}).get("whisper_text"),
                      "ctc_text": (s or {}).get("ctc_text"), "wr_ctc": v.get("wr_ctc"),
                      "vocal_share": v.get("vocal_share"), "wordless": v.get("wordless"),
                      "guide_copy": v.get("guide_copy"), "peak_before_norm": (g or {}).get("peak_before_norm"),
                      "gen_seconds": (g or {}).get("gen_seconds"), "clock_calls": (g or {}).get("hook_calls"),
                      **files.get(run["run_id"], {})})
    kept = {}
    for recipe in dict.fromkeys(t["recipe"] for t in takes):
        mine = [t for t in takes if t["recipe"] == recipe and t["status"] == "scored"]
        kept[recipe] = S.kept(mine)["run_id"] if mine else None
    return {"tool": plan["tool"], "what": "a creator tool on Run B's recipe S* (oohs_k3_A8); not a study, nothing "
            "registered", "utc": utc(), "settings": plan["settings"], "warnings": plan["warnings"],
            "item": item, "guide": plan["guide"], "recipe": plan["recipe"], "seeds": plan["seeds"],
            "code": plan["code"], "scorer": scorer,
            "cpu_test": plan["settings"]["device"] != "cuda" or bool(scorer.get("test_flags")),
            "measures": {"q": "gate x min(NPA_v, WR); joint: q >= 0.5, strict: q >= 0.75 (B2's)",
                         "notes_right": "NPA_v: notes sung on pitch (+-50 cents, the written octave) on the htdemucs "
                                        "vocal stem", "words_recognised": "WR: lyric words Whisper heard, in order",
                         "selector": "largest q; ties: higher WR, higher NPA_v, lower draw (B2's)"},
            "kept": kept, "takes": takes}


def table(doc: dict) -> str:
    rows = [f"{'take':>4s}  {'recipe':8s} {'q':>5s}  {'notes':>6s} {'words':>6s}  gate  Whisper heard"]
    for t in ordered(doc):
        star = "*" if t["run_id"] in doc["kept"].values() else " "
        heard = (t["whisper_text"] or "").strip() if t["status"] == "scored" else f"({t['status']})"
        rows.append(f"{t['take']:>3d}{star}  {t['recipe']:8s} {t['q']:5.2f}  {t['notes_right']:>6s} "
                    f"{t['words_recognised']:>6s}  {'yes ' if t['gate'] else 'no  '}  {heard[:70]}")
    return "\n".join(rows + ["* the take B2's selector keeps (the largest q)"])


def ordered(doc: dict) -> list[dict]:
    """Kept clock take first, then the other clock takes, then the kept no-clock take and the others."""
    out = []
    for recipe, kept in doc["kept"].items():
        mine = [t for t in doc["takes"] if t["recipe"] == recipe]
        out += [t for t in mine if t["run_id"] == kept] + [t for t in mine if t["run_id"] != kept]
    return out


def to_mp3(wav: Path) -> Path | None:
    if shutil.which("ffmpeg") is None:
        return None
    mp3 = wav.with_suffix(".mp3")
    if mp3.exists() and mp3.stat().st_mtime >= wav.stat().st_mtime:
        return mp3
    r = subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-codec:a", "libmp3lame", "-b:a", "192k",
                        str(mp3)], capture_output=True, text=True)
    return mp3 if r.returncode == 0 else None


def score(rundir: Path, device: str, test_whisper: str | None) -> int:
    import score_b2 as S

    plan = read(rundir / "plan.json")
    if plan is None:
        raise SetupError(f"no plan.json in {rundir}")
    if device == "cuda" and test_whisper:
        raise SetupError("on the GPU the tool scores with B2's Whisper large-v3; --test-whisper is for the CPU")
    if device != "cuda" and not test_whisper:
        test_whisper = CPU_WHISPER
    gens = last_rows(rundir / "ledger.jsonl")
    path = rundir / "scores.jsonl"
    old = last_rows(path)
    want = test_whisper or R.WHISPER
    ok = [r for r in plan["runs"] if gens.get(r["run_id"], {}).get("status") == "ok"]
    todo = [r for r in ok if not (old.get(r["run_id"]) and "error" not in old[r["run_id"]]
                                  and old[r["run_id"]].get("wav_sha256") == gens[r["run_id"]]["wav_sha256"]
                                  and old[r["run_id"]].get("whisper") == want)]
    sc = None
    if todo:
        try:
            sc = S.B2Scorer(device, test_whisper=test_whisper)
        except Exception as exc:
            raise SetupError(f"the scorer did not load: {exc!r}") from exc
    guide = P.guide_path(rundir, ITEM_ID, "oohs")
    for run in todo:
        g = gens[run["run_id"]]
        t0 = time.time()
        try:
            row = sc.measure(rundir / f"{run['run_id']}.wav", plan["item"], [], guide)
        except Exception as exc:  # the take counts as unscored
            row = {"error": repr(exc), "traceback": traceback.format_exc()}
        row.update(run_id=run["run_id"], wav_sha256=g["wav_sha256"], whisper=row.get("whisper", want),
                   seconds_total=round(time.time() - t0, 2), utc=utc())
        append_jsonl(path, row)
        print(f"{run['run_id']:>15s} scored in {row['seconds_total']:.1f} s" +
              (f" FAILED: {row['error']}" if "error" in row else ""), flush=True)
    scores = last_rows(path)
    any_row = next((s for s in scores.values() if "error" not in s), {})
    scorer = {"whisper": any_row.get("whisper", want), "whisper_revision": any_row.get("whisper_revision"),
              "ctc": any_row.get("ctc", S.CTC), "ctc_revision": any_row.get("ctc_revision"),
              "test_flags": any_row.get("test_flags", [] if not test_whisper else [f"test whisper {test_whisper}"]),
              "registered_whisper": R.WHISPER, "registered_whisper_revision": R.WHISPER_REVISION}
    files = {}
    for run in ok:
        wav = rundir / f"{run['run_id']}.wav"
        mp3 = to_mp3(wav)
        files[run["run_id"]] = {"wav": wav.name, "mp3": mp3.name if mp3 else None}
    doc = result_doc(plan, gens, scores, scorer, files)
    kept = doc["kept"].get("clock")
    if kept:
        for ext in ("wav", "mp3"):
            src = rundir / f"{kept}.{ext}"
            if src.exists():
                shutil.copyfile(src, rundir / f"kept.{ext}")
    doc["kept_files"] = {"clock": "kept.wav" if kept else None}
    write(rundir / "sing_result.json", doc)
    print(table(doc), flush=True)
    if doc["cpu_test"]:
        print(f"CPU test: scored with {scorer['whisper']}, not B2's {R.WHISPER}; the scores show that the chain runs, "
              "not how well it sings", flush=True)
    print(f"results in {rundir}", flush=True)
    return 0


