def call(py: str, args: list[str], log: Path) -> int:
    sys.path.insert(0, str(ROOT / "experiments" / "e5_motif"))
    from stage import Echo  # the filter run_b.py uses: ACE-Step's info lines stay in the log

    cmd = [py, str(Path(__file__).resolve()), *args]
    echo = Echo()
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("a") as fh:
        fh.write(f"\n$ {' '.join(cmd)}\n")
        fh.flush()
        p = subprocess.Popen(cmd, cwd=ROOT, env=env(), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in p.stdout:
            fh.write(line)
            if echo.show(line) or OWN_LINE.match(line):   # the tool's own lines always reach the user
                print(line, end="", flush=True)
        p.wait()
    return p.returncode


