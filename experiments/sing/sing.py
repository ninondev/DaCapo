def make_runs(item: dict, draws: int, seed: int, voice: str, compare: bool) -> list[dict]:
    """B2's run structure (plan_b2.make_run) for S*, then, with compare, for S*_b0; every draw's two runs share
    its seeds. Only the seeds, the caption's voice, the stage and the run id differ from a B2 run."""
    out = []
    for cid in [S_STAR] + ([S_B0] if compare else []):
        label = "S*" if cid == S_STAR else "S*_b0"
        for r in range(int(draws)):
            run = P.make_run("test", "full", item, r, P.parse(cid), [label])
            dit, rng = seeds(seed, r)
            run.update(run_id=run_id(r, cid), stage="sing", dit_seed=dit, rng_seed=rng, caption=caption(voice),
                       take=r + 1, recipe=RECIPES[cid])
            out.append(run)
    return out


