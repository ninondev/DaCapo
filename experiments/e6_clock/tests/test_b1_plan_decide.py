def test_verdicts(tmp_path, monkeypatch):
    """decide end to end on synthetic ledgers: supported, not supported, technical and test only."""
    out, res = tmp_path / "out", tmp_path / "res"
    monkeypatch.setattr(B.os, "fsync", lambda fd: None)  # 1,440 ledger rows; durability is not under test here

    def write(err, gen_flags=(), calls=None):
        for p in (out / "ledger.jsonl", res / "b1_scores.jsonl"):
            p.unlink(missing_ok=True)
        for run in PLAN:
            (out / f"{run['run_id']}.wav").parent.mkdir(parents=True, exist_ok=True)
            (out / f"{run['run_id']}.wav").write_bytes(run["run_id"].encode())
            (out / f"{run['run_id']}.latents.npy").write_bytes(b"x" + run["run_id"].encode())
            g = _gen(run, flags=gen_flags, calls=calls if run["arm"] == "align2" else None)
            g.update(wav_sha256=B.sha256(out / f"{run['run_id']}.wav"),
                     latents_sha256=B.sha256(out / f"{run['run_id']}.latents.npy"))
            B.append_jsonl(out / "ledger.jsonl", g)
            e = err(run)
            B.append_jsonl(res / "b1_scores.jsonl", {**_score(run, 1.0 if e is None else e, share=0.0 if e is None else 0.9),
                                                     "wav_sha256": g["wav_sha256"]})

    def verdict(scale="full"):
        monkeypatch.setattr(B, "code_state", lambda: STATE)
        monkeypatch.setattr(B, "gate_check", lambda: GATE)
        args = type("A", (), {"out": str(out), "res": str(res), "scale": scale, "unregistered": False, "test_whisper": None})
        B.decide(args)
        return json.loads((res / "b1_result.json").read_text())["results"]

    write(_errors(primary=0.5, improved_items=12, random=0.9))
    r = verdict()
    assert r["verdict"] == "supported" and r["labels"] == ["words moved toward their notes", "recall and voice kept",
                                                           "head-specific"]
    assert r["dose_response"]["align1"]["n_improved"] == 12 and len(r["clips"]) == 180
    write(_errors(primary=0.5, improved_items=12, random=0.5))
    r = verdict()
    assert r["verdict"] == "not supported" and r["reasons"] == ["c3_random_heads failed"]
    write(_errors(primary=0.5, improved_items=12, random=0.9), calls=39)
    assert verdict()["verdict"] == "technical"
    write(_errors(primary=0.5, improved_items=12, random=0.9), gen_flags=["scale tiny"])
    assert verdict()["verdict"] == "test only"


def test_ledger_survives_a_cut_line(tmp_path):
    p = tmp_path / "l.jsonl"
    B.append_jsonl(p, {"run_id": "a", "status": "ok"})
    with open(p, "a") as f:
        f.write('{"run_id": "b", "sta')  # a crash in the middle of a line
    B.append_jsonl(p, {"run_id": "c", "status": "failed"})
    assert [r["run_id"] for r in B.read_jsonl(p)] == ["a", "c"]


