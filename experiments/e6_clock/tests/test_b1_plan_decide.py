def test_tiny_plan_and_written_onsets():
    from dacapo.seeds import run_seeds
    tiny = B.plan("tiny")
    assert [x["run_id"] for x in tiny] == list(B.TINY)
    # the tiny scale has its own seeds: no registered B1 run, E6 run or CPU-test seed is generated by a code test
    registered = {s for x in PLAN for s in (x["dit_seed"], x["rng_seed"])}
    e6 = {61000 + 10 * i + r for i in range(12) for r in range(4)} | {62000 + 100 * v + 10 * w + r for v in range(4)
                                                                       for w in range(2) for r in range(5)}
    taken = registered | e6 | {s + readout.RNG_OFFSET for s in e6} | {6000, 6001, 6002, 906000, 906001, 906002}
    for x in tiny:
        assert (x["dit_seed"], x["rng_seed"]) == run_seeds(B.TINY_TAG, x["item"], x["draw"])
        assert not {x["dit_seed"], x["rng_seed"]} & taken
    assert len({(x["dit_seed"], x["rng_seed"]) for x in tiny}) == 1   # one draw, shared by both arms
    w = B.written_onsets(ITEMS["item00"])
    assert w[:3] == [2.4, 3.0, 3.6] and w[-1] == 11.4 and len(w) == len(lyric_words(ITEMS["item00"]["lyrics"]))


# synthetic clips: Whisper hears every word `err` seconds after its written onset (or drops some words)

def _gen(run, peak=0.5, calls=None, code=None, registered=True, flags=()):
    hooked = run["arm"] != "nohook"
    return {**{k: run[k] for k in ("run_id", "item", "draw", "arm", "beta")}, "status": "ok", "peak_before_norm": peak,
            "hook_calls": (40 if hooked else 0) if calls is None else calls, "max_key": 23 if hooked else None,
            "n_lyr": 26, "lq_lk": [[175, 140, 40]] if hooked else [], "code_sha256": CODE if code is None else code,
            "registered": registered, "test_flags": list(flags), "wav_sha256": "w" + run["run_id"]}


def _score(run, err, n_words=None, share=0.9, whisper=readout.WHISPER, rev=readout.WHISPER_REVISION, flags=()):
    it = ITEMS[run["item"]]
    words, w = lyric_words(it["lyrics"]), B.written_onsets(it)
    k = len(words) if n_words is None else n_words
    return {"run_id": run["run_id"], "wav_sha256": "w" + run["run_id"], "vocal_active_s": 5.0,
            "stem_share": {"vocals": share, "drums": 1 - share, "bass": 0.0, "other": 0.0}, "whisper": whisper,
            "whisper_revision": rev, "test_flags": list(flags),
            "whisper_chunks": [[" " + x, w[j] + err, w[j] + err + 0.3] for j, x in enumerate(words[:k])]}


def _decide(err, gens=None, scores=None, state=STATE, gate=GATE, skip=()):
    """err(run) -> seconds, or None for a clip that fails the gate."""
    gens = {} if gens is None else gens
    scores = {} if scores is None else scores
    for run in PLAN:
        if run["run_id"] in skip:
            continue
        gens.setdefault(run["run_id"], _gen(run))
        e = err(run)
        scores.setdefault(run["run_id"], _score(run, 1.0 if e is None else e, share=0.0 if e is None else 0.9))
    rows = B.clip_rows("full", gens, scores)
    items = sorted({r["item"] for r in rows})
    table = B.item_table(rows)
    arms = {a: B.arm_summary(rows, table, a, items) for a, _, _ in B.ARMS}
    return rows, arms, B.rule(arms), B.integrity(rows, state, gate)


def _errors(primary=0.7, improved_items=9, random=1.0, b0=1.0):
    """beta 0 errs b0 s; align2 improves `improved_items` items to primary * b0; random2 stays at `random` * b0."""
    def err(run):
        i = int(run["item"][4:])
        if run["arm"] == "nohook":
            return b0
        if run["arm"] == "random2":
            return random * b0
        return primary * b0 if i < improved_items else b0
    return err


def test_thirty_percent_exactly_counts_and_nine_items_are_enough():
    rows, arms, cond, problems = _decide(_errors(primary=0.7, improved_items=9))
    assert problems == [] and len(rows) == 180 and all(r["evaluable"] for r in rows)
    assert [x["reduction"] for x in arms["align2"]["items"]] == [0.3] * 9 + [0.0] * 3  # 1 - 0.7/1.0, rounded
    assert cond["c1_items_improved"]["held"] and cond["c1_items_improved"]["n_improved"] == 9
    assert arms["align2"]["median_reduction"] == 0.3 and cond["c3_random_heads"]["held"]
    _, arms, cond, _ = _decide(_errors(primary=0.7, improved_items=8))
    assert not cond["c1_items_improved"]["held"] and arms["align2"]["n_improved"] == 8
    _, arms, cond, _ = _decide(_errors(primary=0.71, improved_items=12))
    assert arms["align2"]["n_improved"] == 0 and not cond["c1_items_improved"]["held"]


def test_items_without_an_evaluable_draw_are_not_improved_and_enter_medians_as_zero():
    def err(run):  # align2 is perfect but fails the gate on items 0-6: those items are not improved
        if run["arm"] == "align2":
            return None if int(run["item"][4:]) < 7 else 0.2
        return 1.0
    _, arms, cond, _ = _decide(err)
    red = arms["align2"]["items"]
    assert sum(x["not_improved"] for x in red) == 7 and arms["align2"]["n_improved"] == 5
    assert arms["align2"]["median_reduction"] == 0.0  # seven zeros and five 0.8s
    assert not cond["c1_items_improved"]["held"]
    assert arms["align2"]["gate_rate"] == round(15 / 36, 6) and not cond["c2_recall_and_gate"]["held"]


def test_item_error_is_the_median_over_evaluable_draws():
    def err(run):
        if run["arm"] == "nohook":
            return {0: 1.0, 1: 2.0, 2: None}[run["draw"]]
        return {0: 0.2, 1: 0.6, 2: 5.0}[run["draw"]]
    rows, arms, _, _ = _decide(err)
    t = B.item_table(rows)
    assert t["nohook"]["item00"]["error"] == 1.5 and t["nohook"]["item00"]["n_evaluable"] == 2
    assert t["align2"]["item00"]["error"] == 0.6 and arms["align2"]["items"][0]["reduction"] == 0.6


def test_recall_and_gate_guards_at_the_boundary():
    base = {"n_improved": 9, "median_reduction": 0.4}
    arms = {"nohook": {"recall": 0.5, "gate_rate": 0.8}, "align2": {**base, "recall": 0.4, "gate_rate": 0.7},
            "random2": {"median_reduction": 0.1}}
    c = B.rule(arms)
    assert c["c2_recall_and_gate"]["held"] and c["c2_recall_and_gate"]["recall_change"] == -0.1  # 0.4 - 0.5 rounds to -0.1
    arms["align2"]["recall"] = 0.399999
    assert not B.rule(arms)["c2_recall_and_gate"]["held"]
    arms["align2"].update(recall=0.5, gate_rate=0.699999)
    assert not B.rule(arms)["c2_recall_and_gate"]["held"]


def test_random_arm_must_stay_below_half():
    arms = {"nohook": {"recall": 1.0, "gate_rate": 1.0},
            "align2": {"n_improved": 12, "median_reduction": 0.4, "recall": 1.0, "gate_rate": 1.0},
            "random2": {"median_reduction": 0.2}}
    assert not B.rule(arms)["c3_random_heads"]["held"]  # equal to half: not below
    arms["random2"]["median_reduction"] = 0.199999
    assert B.rule(arms)["c3_random_heads"]["held"]
    arms["align2"]["median_reduction"], arms["random2"]["median_reduction"] = -0.2, -0.1
    assert not B.rule(arms)["c3_random_heads"]["held"]
    _, _, cond, _ = _decide(_errors(primary=0.5, improved_items=12, random=0.8))  # random 0.2 < half of 0.5
    assert cond["c3_random_heads"]["held"] and cond["c3_random_heads"]["half_of_primary"] == 0.25
    _, _, cond, _ = _decide(_errors(primary=0.5, improved_items=12, random=0.75))  # random 0.25 = half
    assert not cond["c3_random_heads"]["held"]


def test_missing_runs_count_as_recall_zero_and_gate_fail_and_block_above_nine():
    skip = {x["run_id"] for x in PLAN if x["arm"] == "align2"}
    some = set(sorted(skip)[:9])
    rows, arms, _, problems = _decide(_errors(), skip=some)
    assert problems == [] and arms["align2"]["recall"] == round(27 / 36, 6) and arms["align2"]["gate_rate"] == 0.75
    rows, _, _, problems = _decide(_errors(), skip=set(sorted(skip)[:10]))
    assert any(p.startswith("incomplete: 10 of 180") for p in problems)
    assert sum(r["status"] == "missing" for r in rows) == 10


def test_integrity_failures():
    run0 = PLAN[1]  # item00_r0_align1
    cases = {
        "hook calls": ({run0["run_id"]: _gen(run0, calls=39)}, {}),
        "no-hook calls": ({PLAN[0]["run_id"]: _gen(PLAN[0], calls=40)}, {}),
        "peak": ({run0["run_id"]: _gen(run0, peak=None)}, {}),
        "code": ({run0["run_id"]: _gen(run0, code={**CODE, "dacapo/attn_bias.py": "c" * 64})}, {}),
        "reference": ({}, {run0["run_id"]: _score(run0, 1.0, whisper="openai/whisper-small")}),
        "revision": ({}, {run0["run_id"]: _score(run0, 1.0, rev="0" * 40)}),
    }
    for name, (g, s) in cases.items():
        _, _, _, problems = _decide(_errors(), gens=dict(g), scores=dict(s))
        assert len(problems) == 1, (name, problems)
    _, _, _, problems = _decide(_errors(), gate=(False, "E6 GATE: B1 skipped (no gate file)"))
    assert problems and "check-gate" in problems[0]
    bad = {**STATE, "problems": ["the B1 code differs from the B1 code addendum: ['dacapo/attn_bias.py']"]}
    assert _decide(_errors(), state=bad)[3][0].startswith("the B1 code differs")


