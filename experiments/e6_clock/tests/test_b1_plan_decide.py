def test_plan_has_the_registered_180_runs():
    assert len(PLAN) == 180 and [x["run_id"] for x in PLAN[:5]] == [f"item00_r0_{a}" for a, _, _ in B.ARMS]
    assert [(x["item"], x["draw"]) for x in PLAN[::5]] == [(f"item{i:02d}", r) for i in range(12) for r in range(3)]
    b1 = ADD2["b1"]
    assert b1["n_runs"] == len(PLAN) and b1["betas"] == [0, 1, 2, 4] and b1["primary_beta"] == 2
    for x in PLAN:
        i = int(x["item"][4:])
        assert x["dit_seed"] == 63000 + 10 * i + x["draw"] and x["rng_seed"] == x["dit_seed"] + 900000
        assert x["caption"] == readout.CAPTION_F and x["duration"] == 14.0 and x["bpm"] == 100
        assert x["keyscale"] == ITEMS[x["item"]]["key"] and x["lyrics"] == ITEMS[x["item"]]["lyrics"]
        heads = None if x["heads"] is None else {int(L): h for L, h in x["heads"].items()}
        if x["arm"] == "nohook":
            assert x["beta"] == 0 and heads is None
        elif x["arm"].startswith("align"):
            assert heads == readout.ALIGN == {int(L): h for L, h in b1["heads"].items()}
            assert x["beta"] == float(x["arm"][-1])
        else:
            reg = {int(L): h for L, h in b1["random_sets_by_draw"][x["draw"]].items()}
            assert x["arm"] == "random2" and x["beta"] == 2.0 and heads == reg == readout.random_head_sets()[x["draw"]]
    by_draw = {}
    for x in PLAN:  # all arms of a draw share both seeds; draws and items do not
        by_draw.setdefault((x["item"], x["draw"]), set()).add((x["dit_seed"], x["rng_seed"]))
    assert all(len(v) == 1 for v in by_draw.values()) and len({next(iter(v)) for v in by_draw.values()}) == 36


